import { build } from "esbuild";
import { mkdir, readFile, readdir, writeFile, rename } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
const output = "../../Sources/Scribbit/Resources";
await mkdir(output, { recursive: true });
await build({
  entryPoints: ["editor.js"],
  bundle: true,
  minify: true,
  legalComments: "inline",
  plugins: [
    {
      name: "no-disabled-math-fonts",
      setup(build) {
        build.onLoad({ filter: /katex\.min\.css$/ }, () => ({
          contents: "/* Math feature disabled; no KaTeX fonts are loaded. */",
          loader: "css",
        }));
      },
    },
  ],
  format: "iife",
  outfile: `${output}/MilkdownEditor.js`,
  target: ["safari17"],
  sourcemap: false,
});
const css = await readFile(`${output}/MilkdownEditor.css`, "utf8");
if (/https?:\/\//.test(css)) throw new Error("Unexpected remote CSS resource");
await rename(`${output}/MilkdownEditor.css`, `${output}/MilkdownStyle.css`);
const lock = JSON.parse(await readFile("package-lock.json", "utf8"));
const notices = [
  "Milkdown editor bundled runtime dependency notices",
  "",
  "Generated by WebEditor/Milkdown/build.mjs. Build tools are not bundled.",
  "",
];
const runtime = [];
for (const [name, metadata] of Object.entries(lock.packages)) {
  if (!name || metadata.dev) continue;
  const dir = path.resolve(name);
  const pkg = JSON.parse(
    await readFile(path.join(dir, "package.json"), "utf8"),
  );
  const files = (await readdir(dir)).sort();
  const license = files.find((file) => /^licen[sc]e(\.|$)/i.test(file));
  const fallback =
    pkg.name === "remark-math" ? "licenses/remark-math-LICENSE" : null;
  if (!license && !fallback) throw new Error(`Missing license: ${name}`);
  const text = await readFile(
    license ? path.join(dir, license) : fallback,
    "utf8",
  );
  notices.push(
    `===== ${pkg.name}@${pkg.version} (${pkg.license}) =====`,
    text,
    "",
  );
  runtime.push({ name: pkg.name, version: pkg.version, license: pkg.license });
}
await writeFile(
  `${output}/MilkdownNotices.txt`,
  notices.join("\n").trimEnd() + "\n",
);
await writeFile(
  "runtime-dependencies.json",
  JSON.stringify(runtime, null, 2) + "\n",
);

const inputs = [
  "WebEditor/Milkdown/editor.js",
  "WebEditor/Milkdown/style.css",
  "WebEditor/Milkdown/package.json",
  "WebEditor/Milkdown/package-lock.json",
  "WebEditor/Milkdown/build.mjs",
  "Sources/Scribbit/Resources/MilkdownIndex.html",
  "Sources/Scribbit/Resources/MilkdownEditor.js",
  "Sources/Scribbit/Resources/MilkdownStyle.css",
  "Sources/Scribbit/Resources/MilkdownNotices.txt",
];
const hashes = {};
for (const file of inputs)
  hashes[file] = createHash("sha256")
    .update(await readFile(`../../${file}`))
    .digest("hex");
await writeFile(
  `${output}/MilkdownAssets.json`,
  JSON.stringify({ version: 1, sha256: hashes }, null, 2) + "\n",
);
